"""Generate runtime/gi/enums.js from GNOME Shell / Mutter GIR files.

The GIRs can be regenerated from an installed GNOME Shell with
  g-ir-generate /usr/lib64/mutter-18/Clutter-18.typelib > Clutter-18.gir
(and likewise for Cogl, Meta, Mtk, St, Shell).

Usage: tools/gen-gi-enums.py GIR_DIR > runtime/gi/enums.js
"""
import glob
import json
import os
import sys
import xml.etree.ElementTree as ET

CORE = '{http://www.gtk.org/introspection/core/1.0}'
NAMESPACES = ['Clutter', 'Cogl', 'Meta', 'Mtk', 'St', 'Shell']


def main():
    gir_dir = sys.argv[1]
    out = {}
    for ns in NAMESPACES:
        paths = sorted(glob.glob(os.path.join(gir_dir, f'{ns}-*.gir')))
        if not paths:
            continue
        root = ET.parse(paths[-1]).getroot()
        namespace = root.find(f'{CORE}namespace')
        data = {}
        for node in namespace:
            if node.tag in (f'{CORE}enumeration', f'{CORE}bitfield'):
                members = {}
                for m in node.findall(f'{CORE}member'):
                    members[m.get('name').upper()] = int(m.get('value'))
                data[node.get('name')] = members
            elif node.tag == f'{CORE}constant':
                value = node.get('value')
                ctype = node.find(f'{CORE}type')
                tname = ctype.get('name') if ctype is not None else ''
                if tname in ('gint', 'guint', 'gint32', 'guint32', 'gint64', 'guint64', 'gsize'):
                    data[node.get('name')] = int(value)
                elif tname in ('gdouble', 'gfloat'):
                    data[node.get('name')] = float(value)
                elif tname in ('utf8', 'gchar*'):
                    data[node.get('name')] = value
                elif tname == 'gboolean':
                    data[node.get('name')] = value == 'true'
        out[ns] = data

    print('// SPDX-License-Identifier: GPL-3.0-or-later')
    print('// Generated by tools/gen-gi-enums.py from the GNOME Shell 50 GIRs. Do not edit.')
    print('// Enumerations, flags and constants of the GNOME Shell private namespaces.')
    print()
    for ns, data in out.items():
        print(f'export const {ns} = {json.dumps(data, sort_keys=True, separators=(",", ":"))};')
        print()


if __name__ == '__main__':
    main()
