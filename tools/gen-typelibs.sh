# Generate runtime/gi/typelibs.js: empty typelibs for the GNOME Shell private
# namespaces. They only reserve the names so `gi://St` resolves; gnosh fills
# the namespace objects with its GTK-based implementation at startup.
# Needs gi-compile-repository (glib >= 2.80) or g-ir-compiler.
set -eu
VERSION=${1:-18}
out=runtime/gi/typelibs.js
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
compiler=$(command -v gi-compile-repository || command -v g-ir-compiler)
{
    echo '// SPDX-License-Identifier: GPL-3.0-or-later'
    echo '// Generated by tools/gen-typelibs.sh. Do not edit.'
    echo '// Empty typelibs that reserve the GNOME Shell namespaces for gnosh.'
    echo
    echo "export const VERSION = '$VERSION';"
    echo 'export const TYPELIBS = {'
    for ns in Clutter Cogl Meta Mtk Shell St; do
        cat > "$tmp/$ns-$VERSION.gir" <<GIR
<?xml version="1.0"?>
<repository version="1.2" xmlns="http://www.gtk.org/introspection/core/1.0" xmlns:c="http://www.gtk.org/introspection/c/1.0">
  <namespace name="$ns" version="$VERSION" c:identifier-prefixes="$ns" c:symbol-prefixes="$(echo "$ns" | tr 'A-Z' 'a-z')">
  </namespace>
</repository>
GIR
        "$compiler" "$tmp/$ns-$VERSION.gir" -o "$tmp/$ns-$VERSION.typelib"
        printf "    '%s': '%s',\n" "$ns" "$(base64 -w0 "$tmp/$ns-$VERSION.typelib")"
    done
    echo '};'
} > "$out"
echo "wrote $out"
